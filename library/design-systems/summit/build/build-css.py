#!/usr/bin/env python3
"""Build css/summit.tokens.css from tokens/*.tokens.json (DTCG).

Summit is dark-first: :root carries the Dark roles, and the Light roles apply when the OS prefers light,
or with <html data-theme="light">. Like Figma's explicit variable modes, any element can pin a mode with
class="summit-dark" or class="summit-light" (the sidebar pins light; image cards pin dark).
Names: primitive.orange.400 -> --summit-orange-400, dark.text.primary -> --summit-text-primary,
type.metric-l -> --summit-type-metric-l-size|line|weight|tracking, radius.xl -> --summit-radius-xl.
Usage: python3 build/build-css.py   (Python 3.8+, no dependencies)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "summit.tokens.css"


def load(name):
    return json.loads((ROOT / "tokens" / f"{name}.tokens.json").read_text())


def ref(v):
    # "{primitive.orange.400}" -> var(--summit-orange-400)
    return "var(--summit-" + v.strip("{}").split(".", 1)[1].replace(".", "-") + ")"


def px(d):
    return f"{d['value']}{d['unit']}" if d["value"] else "0"


def roles(mode):
    return [f"--summit-{g}-{n}: {ref(t['$value'])};" for g, rs in mode.items() for n, t in rs.items()]


def main():
    c, t, l = load("color"), load("typography"), load("layout")
    base = [f"--summit-{f}-{s}: {tok['$value']};" for f, steps in c["primitive"].items() for s, tok in steps.items()]
    fam = ", ".join(f'"{f}"' if " " in f else f for f in t["font"]["family"]["$value"])
    base.append(f"--summit-font: {fam};")
    for n, tok in t["type"].items():
        v, ext = tok["$value"], tok["$extensions"]["summit"]
        base += [f"--summit-type-{n}-size: {px(v['fontSize'])};", f"--summit-type-{n}-line: {ext['lineHeightPx']}px;",
                 f"--summit-type-{n}-weight: {v['fontWeight']};", f"--summit-type-{n}-tracking: {v['letterSpacing']['value']}em;"]
    for g in ("space", "radius"):
        base += [f"--summit-{g}-{n}: {px(tok['$value'])};" for n, tok in l[g].items()]
    for n, tok in l["shadow"].items():
        layers = ", ".join(f"{px(s['offsetX'])} {px(s['offsetY'])} {px(s['blur'])} {px(s['spread'])} {s['color']}" for s in tok["$value"])
        base.append(f"--summit-shadow-{n}: {layers};")
    base += [f"--summit-glass-blur: {px(l['glass']['blur']['$value'])};", f"--summit-glass-opacity: {l['glass']['opacity']['$value']};"]
    dark, light = roles(c["dark"]), roles(c["light"])
    ind = lambda lines, n=2: [" " * n + x for x in lines]
    out = ["/* Generated by build/build-css.py from tokens/*.tokens.json. Do not edit by hand. */", "",
           ":root {", "  color-scheme: dark;"] + ind(base) + ind(dark) + ["}", "",
           "@media (prefers-color-scheme: light) {", '  :root:not([data-theme="dark"]) {', "    color-scheme: light;"] + ind(light, 4) + ["  }", "}", "",
           ':root[data-theme="light"],', ".summit-light {", "  color-scheme: light;"] + ind(light) + ["}", "",
           ".summit-dark {", "  color-scheme: dark;"] + ind(dark) + ["}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
