#!/usr/bin/env python3
"""Build css/lustro.tokens.css from tokens/*.tokens.json (DTCG).

Names: color.light.surface.card -> --lustro-surface-card (light on :root, dark under the dark selectors),
gradient.window-light -> --lustro-gradient-window-light, type.metric -> --lustro-type-metric-size|line|weight|tracking,
radius.card -> --lustro-radius-card, space.12 -> --lustro-space-12, elevation.card -> --lustro-elevation-card.
Usage: python3 build/build-css.py   (Python 3.8+, no dependencies)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "lustro.tokens.css"


def load(name):
    return json.loads((ROOT / "tokens" / f"{name}.tokens.json").read_text())


def color(v):
    if "alpha" in v:
        r, g, b = (round(c * 255) for c in v["components"])
        return f"rgb({r} {g} {b} / {v['alpha']})"
    return v["hex"]


def px(d):
    return f"{d['value']}{d['unit']}" if d["value"] else "0"


def shadow(layers):
    return ", ".join(
        f"{px(s['offsetX'])} {px(s['offsetY'])} {px(s['blur'])} {px(s['spread'])} {color(s['color'])}" for s in layers
    )


def mode_block(group):
    lines = []
    for g, roles in group.items():
        for n, t in roles.items():
            lines.append(f"  --lustro-{g}-{n}: {color(t['$value'])};")
    return lines


def main():
    c, t, l = load("color"), load("typography"), load("layout")
    light, dark = mode_block(c["color"]["light"]), mode_block(c["color"]["dark"])
    shared = [f"  --lustro-gradient-{k}: {v['$value']};" for k, v in c["gradient"].items() if not k.startswith("$")]
    shared.append("  --lustro-gradient-window: var(--lustro-gradient-window-light);")
    fam = ", ".join(f'"{f}"' if " " in f else f for f in t["font"]["family"]["$value"])
    shared.append(f"  --lustro-font: {fam};")
    for n, tok in t["type"].items():
        v, ext = tok["$value"], tok["$extensions"]["lustro"]
        shared += [
            f"  --lustro-type-{n}-size: {px(v['fontSize'])};",
            f"  --lustro-type-{n}-line: {ext['lineHeightPx']}px;",
            f"  --lustro-type-{n}-weight: {v['fontWeight']};",
            f"  --lustro-type-{n}-tracking: {ext['letterSpacingPercent'] / 100}em;",
        ]
    for group in ("radius", "space"):
        for n, tok in l[group].items():
            if not n.startswith("$"):
                shared.append(f"  --lustro-{group}-{n}: {px(tok['$value'])};")
    for n, tok in l["elevation"].items():
        shared.append(f"  --lustro-elevation-{n}: {shadow(tok['$value'])};")

    dark_extra = ["  --lustro-gradient-window: var(--lustro-gradient-window-dark);"]
    out = ["/* Generated by build/build-css.py from tokens/*.tokens.json. Do not edit by hand. */", "",
           ":root {", "  color-scheme: light;"] + light + shared + ["}", "",
           ':root[data-theme="dark"] {', "  color-scheme: dark;"] + dark + dark_extra + ["}", "",
           "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', "    color-scheme: dark;"]
    out += ["  " + x for x in dark + dark_extra] + ["  }", "}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
