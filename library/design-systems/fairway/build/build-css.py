#!/usr/bin/env python3
"""Build css/fairway.tokens.css from tokens/*.tokens.json (DTCG).

Fairway is light-first: :root carries the Light roles, and the Dark roles apply when the OS prefers dark,
or with <html data-theme="dark">. Like Figma's explicit variable modes, any element can pin a mode with
class="fw-light" or class="fw-dark" (the lime Insight card pins Light).
Glass turns opaque when the user asks for reduced transparency or more contrast.
Names match the Figma code syntax: primitive.forest.900 -> --fw-forest-900, light.status.success.fg ->
--fw-status-success-fg, type.heading-1 -> --fw-type-heading-1-size|line|weight|tracking, radius.xl -> --fw-radius-xl.
Usage: python3 build/build-css.py   (Python 3.8+, no dependencies)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "fairway.tokens.css"
P = "--fw"


def load(name):
    return json.loads((ROOT / "tokens" / f"{name}.tokens.json").read_text())


def flat(tree, path=()):
    # nested DTCG groups -> [(("status", "success", "fg"), token), ...]
    for k, v in tree.items():
        if k.startswith("$"):
            continue
        if "$value" in v:
            yield path + (k,), v
        else:
            yield from flat(v, path + (k,))


def value(v):
    # "{primitive.neutral.100}" -> var(--fw-neutral-100); "#RRGGBBAA" stays as is
    if v.startswith("{"):
        return f"var({P}-" + v.strip("{}").split(".", 1)[1].replace(".", "-") + ")"
    return v


def px(d):
    return f"{d['value']}{d['unit']}" if d["value"] else "0"


def roles(mode):
    return [f"{P}-{'-'.join(p)}: {value(t['$value'])};" for p, t in flat(mode)]


def shadow(layers):
    return ", ".join(f"{px(s['offsetX'])} {px(s['offsetY'])} {px(s['blur'])} {px(s['spread'])} {s['color']}" for s in layers)


def main():
    c, t, l = load("color"), load("typography"), load("layout")
    base = [f"{P}-{'-'.join(p)}: {tok['$value']};" for p, tok in flat(c["primitive"])]
    fam = ", ".join(f'"{f}"' if " " in f else f for f in t["font"]["family"]["$value"])
    base.append(f"{P}-font: {fam};")
    for n, tok in t["type"].items():
        v, ext = tok["$value"], tok["$extensions"]["fairway"]
        base += [f"{P}-type-{n}-size: {px(v['fontSize'])};", f"{P}-type-{n}-line: {ext['lineHeightPx']}px;",
                 f"{P}-type-{n}-weight: {v['fontWeight']};", f"{P}-type-{n}-tracking: {v['letterSpacing']['value']}em;"]
    for g in ("space", "radius", "size", "blur"):
        base += [f"{P}-{g}-{n}: {px(tok['$value'])};" for n, tok in l[g].items()]
    for n, tok in l["shadow"].items():
        base.append(f"{P}-shadow-{n}: {shadow(tok['$value'])};")
    light, dark = roles(c["light"]), roles(c["dark"])
    opaque = [f"{P}-surface-glass: var({P}-surface-default);", f"{P}-surface-glass-strong: var({P}-surface-raised);"]
    ind = lambda lines, n=2: [" " * n + x for x in lines]
    out = ["/* Generated by build/build-css.py from tokens/*.tokens.json. Do not edit by hand. */", "",
           ":root {", "  color-scheme: light;"] + ind(base) + ind(light) + ["}", "",
           "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', "    color-scheme: dark;"] + ind(dark, 4) + ["  }", "}", "",
           ':root[data-theme="dark"],', ".fw-dark {", "  color-scheme: dark;"] + ind(dark) + ["}", "",
           ".fw-light {", "  color-scheme: light;"] + ind(light) + ["}", "",
           "/* Glass falls back to opaque surfaces (glassmorphism.md fallbacks). */",
           "@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {",
           # same or higher specificity than every theme selector above, and later in the file
           '  :root, :root[data-theme], :root:not([data-theme="light"]), .fw-light, .fw-dark {'] + ind(opaque, 4) + ["  }", "}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
