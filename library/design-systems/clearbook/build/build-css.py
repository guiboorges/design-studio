#!/usr/bin/env python3
"""Build css/clearbook.tokens.css from tokens/*.tokens.json (DTCG).

Clearbook is dark-first: :root carries the Dark roles, and the Light roles apply when the OS prefers light,
or with <html data-theme="light">. Like Figma's explicit variable modes, any element can pin a mode with
class="clearbook-dark" or class="clearbook-light".
Glass roles (surface/shell, card, raised) are translucent. When the user asks for reduced transparency, or the
browser has no backdrop-filter, they switch to opaque values, so text keeps its measured contrast.
Names: primitive.blue.300 -> --clearbook-blue-300, dark.text.primary -> --clearbook-text-primary,
type.display-kpi -> --clearbook-type-display-kpi-size|line|weight|tracking, radius.xl -> --clearbook-radius-xl.
Usage: python3 build/build-css.py   (Python 3.8+, no dependencies)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "clearbook.tokens.css"
P = "--clearbook"

# Opaque stand-ins for the glass roles (reduced transparency, no backdrop-filter).
SOLID = {
    "dark": {"surface-shell": "#1C1E21", "surface-card": "var(--clearbook-neutral-825)", "surface-raised": "#3B3E43"},
    "light": {"surface-shell": "#F2F3F5", "surface-card": "var(--clearbook-neutral-150)", "surface-raised": "#FFFFFF"},
}


def load(name):
    return json.loads((ROOT / "tokens" / f"{name}.tokens.json").read_text())


def value(v):
    # "{primitive.blue.300}" -> var(--clearbook-blue-300); "#RRGGBBAA" stays as is
    if v.startswith("{"):
        return f"var({P}-" + v.strip("{}").split(".", 1)[1].replace(".", "-") + ")"
    return v


def px(d):
    return f"{d['value']}{d['unit']}" if d["value"] else "0"


def roles(mode):
    return [f"{P}-{g}-{n}: {value(t['$value'])};" for g, rs in mode.items() for n, t in rs.items()]


def shadow(layers):
    out = []
    for s in layers:
        inset = "inset " if s.get("inset") else ""
        out.append(f"{inset}{px(s['offsetX'])} {px(s['offsetY'])} {px(s['blur'])} {px(s['spread'])} {s['color']}")
    return ", ".join(out)


def main():
    c, t, l = load("color"), load("typography"), load("layout")
    base = [f"{P}-{f}-{s}: {tok['$value']};" for f, steps in c["primitive"].items() for s, tok in steps.items()]
    fam = ", ".join(f'"{f}"' if " " in f else f for f in t["font"]["family"]["$value"])
    base.append(f"{P}-font: {fam};")
    for n, tok in t["type"].items():
        v, ext = tok["$value"], tok["$extensions"]["clearbook"]
        base += [f"{P}-type-{n}-size: {px(v['fontSize'])};", f"{P}-type-{n}-line: {ext['lineHeightPx']}px;",
                 f"{P}-type-{n}-weight: {v['fontWeight']};", f"{P}-type-{n}-tracking: {v['letterSpacing']['value']}em;"]
    for g in ("space", "radius", "blur"):
        base += [f"{P}-{g}-{n}: {px(tok['$value'])};" for n, tok in l[g].items()]
    for n, tok in l["shadow"].items():
        base.append(f"{P}-shadow-{n}: {shadow(tok['$value'])};")
    dark, light = roles(c["dark"]), roles(c["light"])
    sd = [f"{P}-{k}: {v};" for k, v in SOLID["dark"].items()]
    sl = [f"{P}-{k}: {v};" for k, v in SOLID["light"].items()]
    ind = lambda lines, n=2: [" " * n + x for x in lines]
    light_sel = ':root[data-theme="light"], .clearbook-light'
    out = ["/* Generated by build/build-css.py from tokens/*.tokens.json. Do not edit by hand. */", "",
           ":root {", "  color-scheme: dark;"] + ind(base) + ind(dark) + ["}", "",
           "@media (prefers-color-scheme: light) {", '  :root:not([data-theme="dark"]) {', "    color-scheme: light;"] + ind(light, 4) + ["  }", "}", "",
           ':root[data-theme="light"],', ".clearbook-light {", "  color-scheme: light;"] + ind(light) + ["}", "",
           ".clearbook-dark {", "  color-scheme: dark;"] + ind(dark) + ["}", "",
           "/* Opaque glass when transparency is reduced or backdrop-filter is unavailable. */"]
    for cond in ("@media (prefers-reduced-transparency: reduce)", "@supports not ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px)))"):
        out += [cond + " {", "  :root, .clearbook-dark {"] + ind(sd, 4) + ["  }",
                "  @media (prefers-color-scheme: light) {", '    :root:not([data-theme="dark"]) {'] + ind(sl, 6) + ["    }", "  }",
                f"  {light_sel} {{"] + ind(sl, 4) + ["  }", "}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
