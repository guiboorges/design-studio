#!/usr/bin/env python3
"""Build css/ember.tokens.css from tokens/*.tokens.json (DTCG).

Ember is light-first: :root carries the Light roles, and the Dark roles apply when the OS prefers dark,
or with <html data-theme="dark">. Like Figma's explicit variable modes, any element can pin a mode with
class="ember-light" or class="ember-dark".
Names: primitive.orange.500 -> --ember-orange-500, light.text.primary -> --ember-text-primary,
type.display-kpi -> --ember-type-display-kpi-size|line|weight|tracking, radius.xl -> --ember-radius-xl.
Usage: python3 build/build-css.py   (Python 3.8+, no dependencies)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "ember.tokens.css"
P = "--ember"


def load(name):
    return json.loads((ROOT / "tokens" / f"{name}.tokens.json").read_text())


def value(v):
    # "{primitive.orange.500}" -> var(--ember-orange-500); "#RRGGBBAA" stays as is
    if v.startswith("{"):
        return f"var({P}-" + v.strip("{}").split(".", 1)[1].replace(".", "-") + ")"
    return v


def px(d):
    return f"{d['value']}{d['unit']}" if d["value"] else "0"


def roles(mode):
    return [f"{P}-{g}-{n}: {value(t['$value'])};" for g, rs in mode.items() for n, t in rs.items()]


def shadow(layers):
    return ", ".join(f"{px(s['offsetX'])} {px(s['offsetY'])} {px(s['blur'])} {px(s['spread'])} {s['color']}" for s in layers)


def main():
    c, t, l = load("color"), load("typography"), load("layout")
    base = [f"{P}-{f}-{s}: {tok['$value']};" for f, steps in c["primitive"].items() for s, tok in steps.items()]
    fam = ", ".join(f'"{f}"' if " " in f else f for f in t["font"]["family"]["$value"])
    base.append(f"{P}-font: {fam};")
    for n, tok in t["type"].items():
        v, ext = tok["$value"], tok["$extensions"]["ember"]
        base += [f"{P}-type-{n}-size: {px(v['fontSize'])};", f"{P}-type-{n}-line: {ext['lineHeightPx']}px;",
                 f"{P}-type-{n}-weight: {v['fontWeight']};", f"{P}-type-{n}-tracking: {v['letterSpacing']['value']}em;"]
    for g in ("space", "radius", "size"):
        base += [f"{P}-{g}-{n}: {px(tok['$value'])};" for n, tok in l[g].items()]
    for n, tok in l["shadow"].items():
        base.append(f"{P}-shadow-{n}: {shadow(tok['$value'])};")
    base.append(f"{P}-hero-gradient: linear-gradient(135deg, var({P}-accent-hero-start), var({P}-accent-hero-end));")
    light, dark = roles(c["light"]), roles(c["dark"])
    ind = lambda lines, n=2: [" " * n + x for x in lines]
    out = ["/* Generated by build/build-css.py from tokens/*.tokens.json. Do not edit by hand. */", "",
           ":root {", "  color-scheme: light;"] + ind(base) + ind(light) + ["}", "",
           "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', "    color-scheme: dark;"] + ind(dark, 4) + ["  }", "}", "",
           ':root[data-theme="dark"],', ".ember-dark {", "  color-scheme: dark;"] + ind(dark) + ["}", "",
           ".ember-light {", "  color-scheme: light;"] + ind(light) + ["}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
